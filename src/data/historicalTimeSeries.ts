/** 各市水质达标率年度统计汇总(全省均值) */
export const qualityYearlySummary = TS_FULL_YEARS.map(year => {
  const values = Object.entries(cityQualityYearly).map(([_, data]) => data[year]).filter((v): v is number => v !== undefined);
  const avg = values.reduce((s, v) => s + v, 0) / values.length;
  const entries = Object.entries(cityQualityYearly).map(([city, data]) => ({ city, rate: data[year]! }));
  entries.sort((a, b) => b.rate - a.rate);
  return { year, avgRate: Math.round(avg * 10) / 10, bestCity: entries[0].city, bestRate: entries[0].rate, worstCity: entries[entries.length - 1].city, worstRate: entries[entries.length - 1].rate };
});
